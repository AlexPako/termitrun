"""Рисунки в уроках (FB9c). Владелец 20.10 об уроке «Паспорт файла»: «крайне непонятное
описание» — восемь понятий в одном абзаце. Схема со стрелками под примером читается сразу.

Рисунок — предформатированные строки по id задачи. Печатается как есть, без переноса, под
уроком персонажа или шпаргалкой: в карточке задания (ui.task_card) и в команде lesson (hook).
Охраны длины урока его не считают, у рисунка свои (tests/test_diagrams.py): ширина строки не
больше MAX_WIDTH (без переноса рисунок обязан влезть в самое узкое окно карточки),
строк не больше MAX_ROWS, id — существующая задача.

Строки пишутся псевдографикой (│ └ ─ ├). Где её нет — уровень plain и basic — тот же рисунок
печатается ASCII-вариантом: rows(..., ascii_only=True) меняет знаки один к одному, поэтому
стрелки не съезжают.
"""
from typing import Dict, List, Tuple

# окно карточки бывает и в 60 колонок; с отступом в 2 знака рисунок обязан влезть и туда
MAX_WIDTH = 58
MAX_ROWS = 14

TO_ASCII = str.maketrans({"│": "|", "└": "`", "─": "-", "├": "|", "┬": "-", "┴": "-",
                          "┌": ",", "┐": ",", "┘": "'", "┼": "+", "→": ">", "←": "<"})

DIAGRAMS: Dict[str, Tuple[str, ...]] = {
    # строка ls -l по колонкам (FB5 п. 25)
    "read_long_list": (
        "d rwx r-x r-x   2   nol   staff   64  Oct 3  tools",
        "│  │   │   │    │    │      │     │    │       └─ имя",
        "│  │   │   │    │    │      │     │    └─ дата изменения",
        "│  │   │   │    │    │      │     └─ размер в байтах",
        "│  │   │   │    │    │      └─ группа",
        "│  │   │   │    │    └─ владелец (это ты)",
        "│  │   │   │    └─ число ссылок — пока не важно",
        "│  │   │   └─ права всех остальных",
        "│  │   └─ права группы",
        "│  └─ права владельца",
        "└─ тип: d — папка, - — файл, l — ссылка",
    ),
}


def rows(task_id: str, ascii_only: bool = False) -> List[str]:
    """Строки рисунка задачи; нет рисунка — пустой список."""
    lines = DIAGRAMS.get(task_id) or ()
    return [line.translate(TO_ASCII) if ascii_only else line for line in lines]
