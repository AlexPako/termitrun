# Приёмы zsh в масках: (D) после маски и т.п. Ключ — как пишется в тексте.
QUALIFIERS: Dict[str, Tuple[str, str]] = {
    "(D)": ("Dot", "точка: скрытые имена начинаются с неё"),
    "(N)": ("Null", "пусто вместо ошибки, если совпадений нет"),
    "(#i)": ("insensitive", "без учёта регистра"),
}


def long_flag(cmd: str, flag: str) -> bool:
    """Длинный флаг — сам полное слово: --help, --ignore-case, -name и -type у find."""
    return flag.startswith("--") or len(flag) > 2


def word(cmd: str, flag: str) -> Optional[str]:
    """Полное слово флага; у длинного флага без записи — само имя без минусов."""
    entry = FLAG_WORDS.get((cmd, flag))
    if entry:
        return entry[0]
    if long_flag(cmd, flag):
        return flag.lstrip("-")
    return None
