def merge(theme: dict) -> None:
    """Влить трек в THEME: копии разделов voices, места трека — свои ключи."""
    theme["tracks"]["sql"] = dict(TRACK)
    tm = theme["tomorrow"]
    tm["places"]["sql"] = TOMORROW["place"]
    tm["bosses"]["boss_sql"] = TOMORROW["boss"]
    voices = dict(theme["voices"])
    voices["names"] = {**voices.get("names", {}), "sql": VOICE_NAME}
    voices["tracks"] = {**voices.get("tracks", {}), "sql": list(TRACK_VOICES)}
    voices["tasks"] = {**voices.get("tasks", {}), **VOICES}
    theme["voices"] = voices
    theme["tasks"].update({k: dict(v, lesson=LESSONS[k], **({"lessons": LESSONS_BY_ENGINE[k]}
                                                            if k in LESSONS_BY_ENGINE else {}))
                           for k, v in TASKS.items()})
    for tid, by in VARIANT_LESSONS.items():
        theme["tasks"][tid]["variant_lessons"] = dict(by)
