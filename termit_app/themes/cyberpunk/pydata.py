def merge(theme: dict) -> None:
    """Влить трек в THEME: копии разделов voices, места трека — свои ключи."""
    theme["reactions"]["pydata"] = {k: list(v) for k, v in REACTIONS.items()}
    tm = theme["tomorrow"]
    tm["tracks"]["pydata"] = list(TOMORROW["tracks"])
    tm["places"]["pydata"] = TOMORROW["place"]
    tm["bosses"]["boss_pylib"] = TOMORROW["boss"]
    voices = dict(theme["voices"])
    voices["names"] = {**voices.get("names", {}), "pydata": VOICE_NAME}
    voices["tracks"] = {**voices.get("tracks", {}), "pydata": list(TRACK_VOICES)}
    voices["tasks"] = {**voices.get("tasks", {}), **VOICES}
    theme["voices"] = voices
    theme["tasks"].update({k: dict(v, lesson=LESSONS[k]) for k, v in TASKS.items()})
