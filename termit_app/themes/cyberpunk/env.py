def merge(theme: dict) -> None:
    """Влить трек в THEME: копии разделов voices, места трека — свои ключи."""
    tm = theme["tomorrow"]
    tm["places"]["env"] = TOMORROW["place"]
    tm["bosses"]["boss_env"] = TOMORROW["boss"]
    voices = dict(theme["voices"])
    voices["names"] = {**voices.get("names", {}), "env": VOICE_NAME}
    voices["tracks"] = {**voices.get("tracks", {}), "env": list(TRACK_VOICES)}
    voices["tasks"] = {**voices.get("tasks", {}), **VOICES}
    theme["voices"] = voices
    theme["tasks"].update({k: dict(v, lesson=LESSONS[k]) for k, v in TASKS.items()})
    for tid, by in VARIANT_LESSONS.items():
        theme["tasks"][tid]["variant_lessons"] = dict(by)
